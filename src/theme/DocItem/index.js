import React, { Suspense } from 'react';
import DocItem from '@theme-original/DocItem';

// ApiItem and its dependencies (code sample generators, Redux...) weigh several MB, so they are split into their
// own chunk and only downloaded by the pages that need them. The static build waits for the chunk, so the
// generated HTML still contains the full API reference.
const ApiItem = React.lazy(() => import('@theme/ApiItem'));

/**
 * Render the pages generated by docusaurus-plugin-openapi-docs with its ApiItem component, and every other
 * page with the original DocItem.
 *
 * ApiItem provides the Redux store the generated API pages need. Setting it as the docItemComponent of a
 * docs instance would make every page of that instance download its code and change their markup.
 *
 * @param {object} props
 * @returns {React.ReactNode}
 */
export default function DocItemWrapper(props) {
    const { frontMatter } = props.content;

    if (frontMatter.api || frontMatter.schema) {
        return (
            <Suspense fallback={null}>
                <ApiItem {...props} />
            </Suspense>
        );
    }

    return <DocItem {...props} />;
}
